#!/usr/bin/env python3
"""Inspect USB serial adapters and generate explicit TETRA udev aliases.

This tool queries udev metadata only. It never opens a serial port, probes a
controller, installs rules, or guesses a cable's motor / power / lidar role.
"""
import argparse
from pathlib import Path
import re
import subprocess
import sys

ROLES = ('motor', 'interface', 'lidar')
RULE_NAME = '99-tetra-usb.rules'
RULE_DIRS = (Path('/usr/lib/udev/rules.d'), Path('/usr/local/lib/udev/rules.d'),
             Path('/run/udev/rules.d'), Path('/etc/udev/rules.d'))


class ConfigurationError(ValueError):
    pass


def inventory():
    devices = []
    nodes = sorted(set(Path('/dev').glob('ttyUSB*')) | set(Path('/dev').glob('ttyACM*')))
    for node in nodes:
        result = subprocess.run(['udevadm', 'info', '--query=property', f'--name={node}'],
                                check=True, text=True, capture_output=True, timeout=5)
        properties = dict(line.split('=', 1) for line in result.stdout.splitlines() if '=' in line)
        if properties.get('ID_BUS') != 'usb':
            raise ConfigurationError(f'{node}: USB 장치 식별 정보가 없습니다. 재연결 후 다시 조회하세요.')
        properties['DEVNAME'] = str(node.resolve(strict=True))
        devices.append(properties)
    return devices


def checked_value(value):
    # udev match values interpret wildcards and assignments interpret $ / %.
    # Do not allow device metadata to turn an exact match into a broad rule.
    if not value or not re.fullmatch(r'[A-Za-z0-9_.:+/@-]+', value):
        raise ConfigurationError('규칙에 사용할 수 없는 장치 식별값입니다. --match path를 검토하세요.')
    return value


def identity(device, mode):
    keys = ['ID_VENDOR_ID', 'ID_MODEL_ID']
    if mode == 'serial':
        if not device.get('ID_SERIAL_SHORT'):
            raise ConfigurationError(f'{device["DEVNAME"]}: 고유 시리얼이 없습니다. '
                                     '허브 위치를 고정하고 --match path를 사용하세요.')
        keys.append('ID_SERIAL_SHORT')
        if device.get('ID_USB_INTERFACE_NUM'):
            keys.append('ID_USB_INTERFACE_NUM')
    elif mode == 'path':
        if not device.get('ID_PATH'):
            raise ConfigurationError(f'{device["DEVNAME"]}: USB 물리 경로가 없습니다.')
        keys.append('ID_PATH')
    else:
        raise ConfigurationError(f'알 수 없는 식별 방식: {mode}')
    return {key: checked_value(device.get(key, '')) for key in keys}


def matches(device, selector):
    return device.get('ID_BUS') == 'usb' and all(device.get(key) == value for key, value in selector.items())


def render_rules(devices, assignments, mode):
    if set(assignments) != set(ROLES):
        raise ConfigurationError('motor, interface, lidar 세 역할의 실제 장치를 각각 지정하세요.')
    if len(set(assignments.values())) != len(ROLES):
        raise ConfigurationError('동일한 장치를 두 역할에 지정할 수 없습니다.')
    by_name = {device['DEVNAME']: device for device in devices}
    selectors = {}
    for role in ROLES:
        name = assignments[role]
        if name not in by_name:
            raise ConfigurationError(f'{role}: {name} 장치가 연결되어 있지 않습니다.')
        selector = identity(by_name[name], mode)
        found = [device['DEVNAME'] for device in devices if matches(device, selector)]
        if found != [name]:
            raise ConfigurationError(f'{role}: 식별값이 여러 장치에 겹칩니다: {", ".join(found)}. '
                                     '허브 위치를 고정하고 --match path를 검토하세요.')
        selectors[role] = selector
    lines = [
        '# Generated by TETRA_ROS2_M/scripts/tetra_usb_ports.py',
        '# Roles were assigned explicitly by the operator; USB numbering is not used to match.',
        '# Install as /etc/udev/rules.d/99-tetra-usb.rules (after 60-serial.rules).',
        '# Keep the same hub sockets AND PC USB port when matching by path.' if mode == 'path'
        else '# Match adapter serial numbers; keep each adapter connected to its assigned robot board.',
        '',
    ]
    for role in ROLES:
        terms = ['SUBSYSTEM=="tty"', 'ENV{ID_BUS}=="usb"']
        terms += [f'ENV{{{key}}}=="{value}"' for key, value in selectors[role].items()]
        terms += ['GROUP="dialout"', 'MODE="0660"', f'SYMLINK+="tetra/{role}"']
        lines += [f'# {role}', ', '.join(terms), '']
    return '\n'.join(lines)


def conflicting_rules(directories=RULE_DIRS):
    # Effective files follow udev's precedence: /etc overrides /run and /usr.
    effective = {}
    for directory in directories:
        for path in sorted(directory.glob('*.rules')):
            effective[path.name] = path
    conflicts = []
    pattern = re.compile(r'SYMLINK\s*(?:\+=|:=|=)\s*"[^"]*\btetra/(?:motor|interface|lidar)\b')
    for name, path in effective.items():
        if name == RULE_NAME or path.resolve() == Path('/dev/null'):
            continue
        for number, line in enumerate(path.read_text().splitlines(), 1):
            if not line.lstrip().startswith('#') and pattern.search(line):
                conflicts.append(f'{path}:{number}')
    return conflicts


def print_inventory(devices):
    if not devices:
        print('USB 시리얼 장치가 없습니다. 로봇의 USB 허브를 이 PC에 연결한 뒤 다시 실행하세요.')
        return
    for device in devices:
        print(device['DEVNAME'])
        for label, key in [('제조사:제품', None), ('고유 시리얼', 'ID_SERIAL_SHORT'),
                           ('USB 인터페이스', 'ID_USB_INTERFACE_NUM'), ('물리 경로', 'ID_PATH'),
                           ('현재 별칭', 'DEVLINKS')]:
            value = (device.get('ID_VENDOR_ID', '?') + ':' + device.get('ID_MODEL_ID', '?')
                     if key is None else device.get(key, '(없음)'))
            print(f'  {label}: {value}')
    print('역할은 자동 판별하지 않습니다. 케이블 라벨 / 보드 연결과 한 개씩 연결한 결과로 구분하세요.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    sub.add_parser('list', help='연결된 USB 시리얼 식별 정보 조회 (모터 명령을 보내지 않음)')
    generate = sub.add_parser('generate', help='역할을 지정하여 검토용 udev 규칙 파일 생성')
    for role in ROLES:
        generate.add_argument(f'--{role}', required=True, help=f'{role} 역할이 확인된 /dev/ttyUSB* 또는 별칭')
    generate.add_argument('--match', choices=['serial', 'path'], default='serial',
                          help='기본: 고유 시리얼. path: 허브 및 PC의 물리 USB 포트 고정')
    generate.add_argument('--output', type=Path, required=True, help='새로 만들 .rules 파일 (기존 파일 덮어쓰기 안 함)')
    args = parser.parse_args()
    try:
        devices = inventory()
        if args.command == 'list':
            print_inventory(devices)
            conflicts = conflicting_rules()
            if conflicts:
                print('기존 별칭 규칙 (새 규칙 등록 전 중복 해소 필요):\n  ' + '\n  '.join(conflicts))
            return 0
        assignments = {role: str(Path(getattr(args, role)).resolve(strict=True)) for role in ROLES}
        rules = render_rules(devices, assignments, args.match)
        conflicts = conflicting_rules()
        if conflicts:
            raise ConfigurationError('동일 별칭을 만드는 기존 규칙을 먼저 확인하세요:\n  ' + '\n  '.join(conflicts))
        output = args.output.expanduser()
        if output.suffix != '.rules':
            raise ConfigurationError('--output은 .rules 파일이어야 합니다.')
        with output.open('x') as stream:
            stream.write(rules)
        for role in ROLES:
            print(f'{assignments[role]} -> /dev/tetra/{role}')
        print(f'규칙 파일 생성: {output.resolve()}')
        print('시스템에는 아직 설치하지 않았습니다. README의 등록·재연결 절차를 따르세요.')
        return 0
    except (ConfigurationError, OSError, subprocess.SubprocessError) as exc:
        print(f'오류: {exc}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
